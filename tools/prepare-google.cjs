const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const core = fs.readFileSync(path.join(root, 'lib', 'attendance.js'), 'utf8');
fs.writeFileSync(path.join(root, 'google', 'Attendance.gs'), core);
fs.writeFileSync(path.join(root, 'docs', 'calendar.js'), core);
const template = fs.readFileSync(path.join(root, 'google', 'Admin.template.html'), 'utf8');
const html = template.replace('/* CALENDAR_SOURCE */', core);
fs.writeFileSync(path.join(root, 'google', 'Admin.html'), html);
// The generated single-file edition makes account setup one source paste.
const backend = fs.readFileSync(path.join(root, 'google', 'Code.gs'), 'utf8');
const legacy = fs.readFileSync(path.join(root, 'google', 'Legacy.gs'), 'utf8');
fs.writeFileSync(
	path.join(root, 'google', 'Purok.gs'),
	'/* Generated by tools/prepare-google.cjs. Paste this file alone into Google Apps Script. */\n' +
		core +
		'\n' +
		backend.replace(
			"HtmlService.createHtmlOutputFromFile('Admin')",
			'HtmlService.createHtmlOutput(ADMIN_HTML_)'
		) +
		'\n' +
		legacy +
		'\nvar ADMIN_HTML_ = ' +
		JSON.stringify(html) +
		';\n'
);
console.log('Shared calendar prepared for Google and GitHub Pages.');
